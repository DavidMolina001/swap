#!/usr/bin/env python3
"""Writes src/Tokens.swift and windows/Tokens.cs from design/tokens.json. Run after any change to the JSON.
Themes (the "themes" section) go to the Mac only; the Windows app keeps the base colours for now."""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design/tokens.json").read_text())

def rgba(s):
    m = re.fullmatch(r"rgba\((\d+),(\d+),(\d+),([\d.]+)\)", s.replace(" ", ""))
    if m:
        r, g, b, a = m.groups(); return ("rgb", int(r), int(g), int(b), float(a))
    m = re.fullmatch(r"accent@([\d.]+)", s)
    if m:
        return ("accent", float(m.group(1)))
    raise SystemExit(f"bad colour {s}")

def swift_color(s):
    c = rgba(s)
    if c[0] == "accent":
        return f"NSColor.controlAccentColor.withAlphaComponent({c[1]})"
    _, r, g, b, a = c
    return f"NSColor(srgbRed: {r}/255, green: {g}/255, blue: {b}/255, alpha: {a})"

def cs_color(s):
    c = rgba(s)
    if c[0] == "accent":
        return f"Accent({int(round(c[1] * 255))})"
    _, r, g, b, a = c
    return f"Color.FromArgb({int(round(a * 255))}, {r}, {g}, {b})"

def num(v):
    return str(v) if isinstance(v, int) else repr(float(v))

WEIGHTS = {"regular": ".regular", "medium": ".medium", "semibold": ".semibold", "bold": ".bold"}
CS_WEIGHTS = {"regular": "FontStyle.Regular", "medium": "FontStyle.Regular", "semibold": "FontStyle.Bold", "bold": "FontStyle.Bold"}

# ---------- Swift ----------
sw = ["// Generated by design/gen-tokens.py from design/tokens.json. Do not edit; change the JSON and re-run.",
      "import AppKit", "",
      "// A colour with a dark and a light value; call it with `dark: true/false`. Theme.color adds the two optional parts:",
      "// the Increase Contrast values, and onAccent for text on the selected row, which goes black on a light accent colour.",
      "struct Shade {", "    let dark: NSColor", "    let light: NSColor",
      "    var contrastDark: NSColor? = nil", "    var contrastLight: NSColor? = nil", "    var onAccent = false",
      "    var key = \"\"   // the token's name, so a theme can replace it",
      "    func callAsFunction(_ dark: Bool) -> NSColor { dark ? self.dark : self.light }",
      "    func contrast(_ dark: Bool) -> NSColor { (dark ? contrastDark : contrastLight) ?? self(dark) }", "}", "",
      "// A colour theme from the \"themes\" section: the colours it replaces, by token name, and its stripes, which are its",
      "// swatch in Settings and, with `band` and `tail`, drawn on the panel (see Theme in Panel.swift).",
      "struct Palette {", "    let id: String", "    let name: String", "    let colors: [String: Shade]", "    let stripes: [Shade]",
      "    let band: Bool   // a stripe band along the panel's top edge",
      "    let tail: Bool   // stripes at the right end of the selected row", "}", "",
      f"enum Tokens {{", f"    static let version = \"{T['meta']['version']}\"", "", "    enum Color {"]
for k, v in T["color"].items():
    note = f"   // {v['note']}" if "note" in v else ""
    extra = ""
    if "contrastDark" in v: extra += f", contrastDark: {swift_color(v['contrastDark'])}, contrastLight: {swift_color(v['contrastLight'])}"
    if v.get("onAccent"): extra += ", onAccent: true"
    sw.append(f"        static let {k} = Shade(dark: {swift_color(v['dark'])}, light: {swift_color(v['light'])}{extra}, key: \"{k}\"){note}")
sw += ["    }", "", "    enum Themes {", f"        static let defaultID = \"{T['themes']['default']}\""]
themes = sorted(((k, v) for k, v in T["themes"].items() if isinstance(v, dict)), key=lambda kv: kv[1]["order"])
if T["themes"]["default"] not in dict(themes): raise SystemExit("themes.default names no theme")
sw.append("        static let all: [Palette] = [")
for k, v in themes:
    for name in v["color"]:
        if name not in T["color"]: raise SystemExit(f"theme {k}: {name} is not a colour token")
    colors = ", ".join(f"\"{n}\": Shade(dark: {swift_color(c['dark'])}, light: {swift_color(c['light'])})" for n, c in v["color"].items())
    stripes = ", ".join(f"Shade(dark: {swift_color(c['dark'])}, light: {swift_color(c['light'])})" for c in v["stripes"])
    sw.append(f"            // {v['note'].split('. ')[0]}. Contrast ratios: tokens.json, themes.{k}.note.")
    sw.append(f"            Palette(id: \"{k}\", name: {json.dumps(v['name'])}, colors: [{colors or ':'}],")
    sw.append(f"                    stripes: [{stripes}], band: {str(v.get('band', False)).lower()}, tail: {str(v.get('tail', False)).lower()}),")
sw += ["        ]",
       "        // The theme with this id, or the default one for an id this version does not know.",
       "        static func named(_ id: String) -> Palette { all.first { $0.id == id } ?? all.first { $0.id == defaultID }! }",
       "    }", "", "    enum Size {"]
for k, v in T["size"].items():
    sw.append(f"        static let {k}: CGFloat = {num(v)}")
sw += ["    }", "", "    enum Font {"]
for k, v in T["type"].items():
    sw.append(f"        static let {k} = NSFont.systemFont(ofSize: {num(v['size'])}, weight: {WEIGHTS[v['weight']]})")
    if "tracking" in v:
        sw.append(f"        static let {k}Tracking: CGFloat = {num(v['tracking'])}")
sw += ["    }", "", "    enum Radius {"]
for k, v in T["radius"].items():
    sw.append(f"        static let {k}: CGFloat = {num(v)}")
sw += ["    }", "", "    enum Motion {"]
for k, v in T["motion"].items():
    if k == "note": continue
    if k.endswith("Ms"):
        sw.append(f"        static let {k[:-2]}: TimeInterval = {v / 1000}")
    else:
        sw.append(f"        static let {k}: CGFloat = {num(v)}")
sw += ["    }", "", "    enum Copy {"]
for k, v in T["copy"].items():
    sw.append(f"        static let {k} = {json.dumps(v, ensure_ascii=False)}" if isinstance(v, str) else f"        static let {k} = {v}")
sw += ["    }", "}", ""]
(ROOT / "src/Tokens.swift").write_text("\n".join(sw))

# ---------- C# (C# 5 only: the compiler that ships with Windows has no => members) ----------
cs = ["// Generated by design/gen-tokens.py from design/tokens.json. Do not edit; change the JSON and re-run.",
      "using System.Drawing;", "", "namespace Swap", "{",
      "    // One colour with a dark and a light value.",
      "    public struct Shade", "    {",
      "        public readonly Color Dark, Light;",
      "        public Shade(Color dark, Color light) { Dark = dark; Light = light; }",
      "        public Color For(bool dark) { return dark ? Dark : Light; }", "    }", "",
      "    public static class Tokens", "    {",
      f"        public const string Version = \"{T['meta']['version']}\";", "",
      "        // The Windows accent colour (set by the app at start-up from UISettings or DwmGetColorizationColor).",
      "        public static Color AccentBase = Color.FromArgb(0, 120, 215);",
      "        static Color Accent(int alpha) { return Color.FromArgb(alpha, AccentBase.R, AccentBase.G, AccentBase.B); }", ""]
for k, v in T["color"].items():
    name = k[0].upper() + k[1:]
    cs.append(f"        public static Shade {name} {{ get {{ return new Shade({cs_color(v['dark'])}, {cs_color(v['light'])}); }} }}")
cs.append("")
for k, v in T["size"].items():
    name = k[0].upper() + k[1:]
    if k in T["color"]: name += "Size"   # C# has one namespace here: "Separator" is a colour and a size
    cs.append(f"        public const float {name} = {float(v)}f;")
cs.append("")
for k, v in T["type"].items():
    name = k[0].upper() + k[1:]
    cs.append(f"        public const float {name}Size = {float(v['size']) * 0.75:.2f}f;   // pt (Segoe UI); {v['size']} px")
    cs.append(f"        public const FontStyle {name}Style = {CS_WEIGHTS[v['weight']]};")
cs.append("")
for k, v in T["radius"].items():
    name = k[0].upper() + k[1:]
    cs.append(f"        public const float Radius{name} = {float(v)}f;")
cs.append("")
for k, v in T["motion"].items():
    if k == "note": continue
    name = k[0].upper() + k[1:]
    cs.append(f"        public const {'int' if isinstance(v, int) else 'float'} {name} = {v}{'' if isinstance(v, int) else 'f'};")
cs.append("")
for k, v in T["copy"].items():
    name = k[0].upper() + k[1:]
    if isinstance(v, str):
        cs.append(f"        public const string {name} = {json.dumps(v.replace('%@', '{0}').replace('%d', '{0}'), ensure_ascii=False)};")
    else:
        cs.append(f"        public const int {name} = {v};")
cs += ["    }", "}", ""]
(ROOT / "windows/Tokens.cs").write_text("\n".join(cs))
print("wrote src/Tokens.swift and windows/Tokens.cs")
